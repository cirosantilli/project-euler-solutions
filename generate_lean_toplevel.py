#!/usr/bin/env python3
from __future__ import annotations

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
LIB_DIR = ROOT / "ProjectEulerSolutions"
EQUIV_DIR = LIB_DIR / "Equiv"
OUTPUT = ROOT / "ProjectEulerSolutions.lean"

IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def module_name(stem: str) -> str:
    if IDENT_RE.match(stem):
        return stem
    return f"«{stem}»"


def sort_key(stem: str):
    if stem.isdigit():
        return (0, int(stem))
    if stem.startswith("P") and stem[1:].isdigit():
        return (0, int(stem[1:]))
    return (1, stem)


def main() -> int:
    lib_stems = [p.stem for p in EQUIV_DIR.glob("P*.lean")]
    lib_stems.sort(key=sort_key)

    lines: list[str] = []
    lines.append("-- This file is autogenerated by generate_lean_toplevel.py; do not edit manually.")
    for stem in lib_stems:
        lines.append(f"import ProjectEulerSolutions.{module_name(stem)}")
        lines.append(f"import ProjectEulerSolutions.Equiv.{module_name(stem)}")

    lines.append("")

    # Preserve each theorem's actual domain, including proof arguments and the
    # shared mathematical references used by the Python source proofs.
    for stem in lib_stems:
        if not stem.startswith("P") or not stem[1:].isdigit():
            continue
        lines.append(f"example := @ProjectEulerSolutions.{stem}.equiv")
        lines.append("")

    OUTPUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
